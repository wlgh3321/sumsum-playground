let LANG = 'ko';

function setLang(l) {
  LANG = DICT[l] ? l : 'ko';
}

function t(key, vars) {
  let s = (DICT[LANG] && DICT[LANG][key]) || DICT.ko[key] || key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  }
  return s;
}

// 초를 읽기 좋게: 30초 / 1분 / 1분 30초 (영어: 30 sec / 1 min / 1 min 30 sec)
function duration(sec) {
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  if (LANG === 'en') {
    if (m === 0) return `${s} sec`;
    return s === 0 ? `${m} min` : `${m} min ${s} sec`;
  }
  if (m === 0) return `${s}${t('secUnit')}`;
  return s === 0 ? `${m}${t('minUnit')}` : `${m}${t('minUnit')} ${s}${t('secUnit')}`;
}

const MODE_NAME_KEY = {
  fall: 'modeFallName',
  minute: 'modeMinuteName',
  race: 'modeRaceName',
  balloon: 'modeBalloonName',
  beat: 'modeBeatName',
  tf: 'modeTfName',
};

// 게임 이름. 1분 도전은 제한 시간에 따라 "2분 도전", "30초 도전"처럼 바뀌어요.
function modeName(id, s) {
  const name = id === 'minute'
    ? t('modeMinuteName', { time: duration(s.time) })
    : t(MODE_NAME_KEY[id]);
  return s && s.ranked ? name + t('rankedSuffix') : name;
}
